cars = ['bmw', 'audi', 'toyota', 'subaru']
cars.sort()
print(cars)
cars.sort(reverse=True) 
print(cars)
cars.sort(reverse=False)
print(cars)
cars.reverse()
print(cars)
length = len(cars)
print(length)
